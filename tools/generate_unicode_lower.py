#!/usr/bin/env python3
"""Regenerate the pinned invariant simple-lowercase lookup; no network access."""
from pathlib import Path
import hashlib
import argparse


def generate(root):
    source = root / 'library/upstream/unicode/16.0.0/UnicodeData.txt'
    mapping = {}
    for line in source.read_text().splitlines():
        fields = line.split(';')
        if fields[13]:
            key, value = int(fields[0], 16), int(fields[13], 16)
            if key != 0x0130:  # pal_casing.c invariant exception, unlike ICU default.
                assert (key <= 0xffff) == (value <= 0xffff)
                mapping[key] = value
    keys = sorted(mapping)
    ranges, index = [], 0
    while index < len(keys):
        start = end = keys[index]
        delta = mapping[start] - start
        step = 1
        if index + 1 < len(keys) and keys[index + 1] - start in (1, 2) and mapping[keys[index + 1]] - keys[index + 1] == delta:
            step = keys[index + 1] - start
        index += 1
        while index < len(keys) and keys[index] == end + step and mapping[keys[index]] - keys[index] == delta:
            end = keys[index]
            index += 1
        ranges.append((start, end, step, delta))
    expanded = {c: c + d for s, e, step, d in ranges for c in range(s, e + 1, step)}
    assert expanded == mapping

    def tree(rows, indent):
        pad = ' ' * indent
        if len(rows) > 1:
            middle = len(rows) // 2
            return (f'{pad}if (scalar < 0x{rows[middle][0]:x})\n{pad}{{\n' + tree(rows[:middle], indent + 4)
                    + f'{pad}}}\n{pad}else\n{pad}{{\n' + tree(rows[middle:], indent + 4) + f'{pad}}}\n')
        start, end, step, delta = rows[0]
        condition = f'scalar == 0x{start:x}' if start == end else f'scalar >= 0x{start:x} && scalar <= 0x{end:x}'
        if step == 2 and start != end:
            condition += f' && ((scalar - 0x{start:x}) & 1) == 0'
        return f'{pad}if ({condition}) return scalar + ({delta});\n{pad}return scalar;\n'

    # Small page methods keep IL bodies and verifier work bounded, without static
    # arrays, retained roots or an allocation on each lookup.
    pages = [ranges[i:i + 24] for i in range(0, len(ranges), 24)]
    body = '// Generated by tools/generate_unicode_lower.py from Unicode 16.0.0.\n'
    body += '// Unicode data license: ../upstream/unicode/16.0.0/LICENSE.txt.\n'
    body += '// UnicodeData SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    body += '// Simple lower mapping with U+0130 unchanged, per pinned .NET invariant casing.\n'
    body += 'namespace Cilica.Runtime\n{\n    internal static class UnicodeSimpleLower\n    {\n        internal static int Map(int scalar)\n        {\n'
    for i in range(len(pages) - 1):
        body += f'            if (scalar < 0x{pages[i + 1][0][0]:x}) return Page{i}(scalar);\n'
    body += f'            return Page{len(pages) - 1}(scalar);\n        }}\n'
    for i, page in enumerate(pages):
        body += f'        private static int Page{i}(int scalar)\n        {{\n' + tree(page, 12) + '        }\n'
    body += '    }\n}\n'
    return body, len(mapping), len(ranges)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    text, mappings, ranges = generate(root)
    output = root / 'library/Cilica.Core/UnicodeSimpleLower.cs'
    if args.check:
        assert output.read_text() == text, 'Regenerate UnicodeSimpleLower.cs'
    else:
        output.write_text(text)
    print(f'{mappings} exact mappings in {ranges} ranges; width and expansion verified')
